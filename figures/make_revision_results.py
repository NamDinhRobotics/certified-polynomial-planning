"""Render tables and a scientific figure directly from the revision artifacts."""
import figstyle
import json
import numpy as np
from revision_claims import HERE,load,invariants,compute
from revision_common import clean,bootstrap_mean_ci
from tiny_comparison import comparison


def table(caption,label,columns,header,rows):
    return ('% Generated by make_revision_results.py; do not edit.\n'
            '\\begin{table}[t]\n\\caption{'+caption+'}\\label{'+label+'}\n'
            '\\centering\\small\n\\begin{tabular}{@{}'+columns+'@{}}\n\\toprule\n'
            +header+r' \\'+'\n\\midrule\n'+'\n'.join(rows)
            +'\n\\bottomrule\n\\end{tabular}\n\\end{table}\n')


def render(data):
    claims=compute(data); c=claims['macros']; files={}
    files['results_revision.tex']='% Generated claim macros.\n'+''.join(
        '\\newcommand{\\'+k+'}{'+v+'}\n' for k,v in c.items())
    rows=[]
    for f in ['F1','F2']:
        rr=data['revision_streaming_'+f]['rows']
        for arm,name in [('plain','Plain SDP'),('onecut','One-cut SDP'),('guide_qp','Guide QPs')]:
            ok=sum(r['arms'][arm]['accepted'] for r in rr)
            rows.append(f'{f} & {name} & {ok} & {1000-ok} & {ok}'+r' \\')
    files['table_revision_streaming.tex']=table(
        'Availability over 20 seeds and 50 instants per seed, per family. All arms use zero requested margin, a numerical gate at $-10^{-9}$, and a terminal no-answer policy. The last column is the offline rational recheck of accepted records, at the same tolerance.',
        'tab:streaming','llrrr','Family & Method & Answer & No answer & Recheck',rows)
    rows=[]
    for f in ['F1','F2']:
        for arm,name in [('plain','Plain SDP'),('onecut','One-cut SDP'),('guide_qp','Guide QPs')]:
            a=[r['arms'][arm]['online_ms'] for r in data['revision_serial_timing']['rows'] if r['family']==f]
            q=np.quantile(a,[.5,.9,.99]); miss=sum(t>100 for t in a)
            rows.append(f'{f} & {name} & {q[0]:.1f} & {q[1]:.1f} & {q[2]:.1f} & {miss}'+r' \\')
    files['table_revision_timing.tex']=table(
        'Serial end-to-end planning time in ms on Apple M5 Pro, macOS arm64, Python 3.12.13. One prespecified frame per seed, five cold repeats: 100 samples per family. Imports and offline rational rechecks are excluded. Miss is the count above 100 ms.',
        'tab:timing','llrrrr','Family & Method & p50 & p90 & p99 & Miss',rows)
    rows=[]
    for pop,name in [('historical_rho1',r'$\rho=1$'),('corner_rho2',r'$\rho=2$')]:
        rr=[r for r in data['revision_frozen']['rows'] if r['population']==pop]
        one=sum(r['onecut']['accepted'] for r in rr); first=[r['bnb_first'] for r in rr if r['bnb_first']]
        end=[r['bnb_end'] for r in rr]
        rows.append(f'{name} ({len(rr)}) & {one} & {len(first)} & {sum(bool(r["solver_proven"]) for r in end)} & '
                    f'{np.median([r["conic_solves"] for r in first]):g} / {np.median([r["conic_solves"] for r in end]):g}'+r' \\')
    files['table_revision_frozen.tex']=table(
        'Same-instance frozen comparison. Answer counts are one-cut / B\\&B first incumbent / B\\&B numerical gap termination. Calls are median conic calls to the first incumbent (among answered instances) / all calls to search termination. The node and soft time limits apply to search, not to one-cut.',
        'tab:frozen','lrrrr','Population ($n$) & Cut & First & Closed & Calls',rows)
    rows=[]; short={'frozen_barrier':'Frozen','sweeping_barrier':'Sweeping','vertical_gate':'Gate','chord1':'Chord 1','chord2':'Chord 2','chord3':'Chord 3'}
    for scene in short:
        for arm,name in [('kkt_one_margin0','One'),('kkt_iterated_margin0','Iter.')]:
            cell=next(r for r in data['revision_tinysdp']['rows'] if r['scene']==scene and r['arm']==arm)
            reps=cell['repeats'];a=[p['total_us']/1000 for r in reps for p in r['plans']]
            success=sum(r['success'] for r in reps); clear=min(r['min_dense'] for r in reps)
            rows.append(f'{short[scene]} & {name} & {success}/5 & {clear:.3f} & {np.median(a):.3f} & {np.quantile(a,.99):.3f}'+r' \\')
    files['table_revision_tiny.tex']=table(
        'TinySDP implementation study: matched all-obstacle KKT variants with zero additional inflation beyond each scene\'s prediction inflation. Clear is the minimum dense interstage tracker diagnostic in metres; times are total planning ms including the common monitor. Every scene has five repeated runs; goal completion is not a continuous safety certificate.',
        'tab:tiny','llrrrr','Scene & QP & Goal & Clear & p50 & p99',rows)
    comp=comparison(data);rows=[]
    for r in comp['revised']:
        a=r['baseline'];b=r['replacement']
        steps=lambda x: '/'.join(str(v) for v in sorted(set(x['goal_steps'])))
        rows.append(f"{short[r['scene']]} & {a['plan_ms']['p50']:.2f} / {b['plan_ms']['p50']:.3f} & "
                    f"{r['speedup']:.0f}$\\times$ & {a['min_dense']:.3f} / {b['min_dense']:.3f} & "
                    f"{steps(a)} / {steps(b)} & {r['effort_ratio']:.2f}$\\times$"+r' \\')
    files['table_revision_tiny_comparison.tex']=table(
        'Revised comparison with the original TinySDP formulation. Each pair is SDP / one-step QP--KKT; the QP requests 1.5 m additional inflation. Both arms reach the goal in all five repeats per scene. Times include prediction, guide, solve and the common monitor. Clear is the minimum sampled interstage tracker clearance. Effort is the ratio of executed $\\sum_k\\|u_k\\|^2$; a ratio above one is worse for the QP. Formulations have different objectives and feasible sets.',
        'tab:tinycomparison','lrrrrr','Scene & p50 planning ms & Time ratio & Clear m & Goal step & Effort QP/SDP',rows).replace('\\begin{table}[t]','\\begin{table*}[t]').replace('\\end{table}','\\end{table*}')
    rows=[]
    for r in comp['historical']:
        rows.append(f"{short[r['scene']]} & {r['baseline_ms']:.2f} / {r['replacement_ms']:.5f} & "
                    f"{r['speedup']:.0f}$\\times$ & {r['baseline_clear']:.3f} / {r['replacement_clear']:.3f}"+r' \\')
    files['table_revision_tiny_history.tex']=table(
        'Archived measurements reported in the original draft: SDP / one-step QP--KKT with 1.5 m additional inflation. These are solve-only times and the older frozen-ball straight-segment clearance diagnostic, not the revised total-planning/dense metrics. All rows reach the goal at step 11. The archive is retained, not relabelled as a new run.',
        'tab:tinyhistory','lrrr','Scene & Solve ms, SDP/QP & Ratio & Clear m, SDP/QP',rows).replace('\\begin{table}[t]','\\begin{table*}[t]').replace('\\end{table}','\\end{table*}')
    files['claims_revision.json']=json.dumps(clean(claims),indent=2,allow_nan=False)+'\n'
    from replanning_results import render as render_replanning
    files.update(render_replanning(data,table))
    return {name:text.replace("[t]", "[!t]") if name.endswith(".tex") else text for name,text in files.items()}


def plot(data):
    import matplotlib;matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    figstyle.use()
    fig,axs=plt.subplots(1,2,figsize=(figstyle.TEXT_W,2.65),layout='constrained')
    colors=['#2874A6','#D97732']; width=.34
    for j,f in enumerate(['F1','F2']):
        x=data['revision_streaming_'+f];rs=x['rows']; vals=[];err=[]
        for arm in ['plain','onecut','guide_qp']:
            rates=[100*np.mean([r['arms'][arm]['accepted'] for r in rs if r['seed']==s]) for s in range(20)]
            b=bootstrap_mean_ci(rates); vals.append(b['mean']);err.append([b['mean']-b['ci95'][0],b['ci95'][1]-b['mean']])
        axs[0].bar(np.arange(3)+(j-.5)*width,vals,width,color=colors[j],label=f,yerr=np.array(err).T,capsize=3)
    axs[0].set_xticks(range(3),['Plain SDP','One-cut','Guide QPs']);axs[0].set_ylim(0,112)
    axs[0].set_ylabel('Available instants (%)');axs[0].legend(loc='upper left',ncol=2,frameon=False)
    pop=compute(data)['populations']
    for j,f in enumerate(['F1','F2']):
        yy=pop[f]['seed_energy_medians'];xx=np.full(20,j)+np.linspace(-.13,.13,20)
        axs[1].scatter(xx,yy,s=17,alpha=.8,c=colors[j]);axs[1].plot([j-.2,j+.2],[np.median(yy)]*2,color=colors[j],lw=2)
    axs[1].axhline(0,color='.5',lw=.7);axs[1].set_xticks([0,1],['F1','F2']);axs[1].set_xlim(-.5,1.5)
    axs[1].set_ylabel('One-cut vs guide energy (%)');axs[1].set_title('(b) One energy median per seed',fontsize=9);axs[0].set_title('(a) Planning availability',fontsize=9)
    figstyle.save(fig,HERE/'fig_revision_streaming')
    plt.close(fig)


