"""Generated manuscript claims and figure from the separately audited quadrotor demo."""
import figstyle
from pathlib import Path
from math import ceil
import contextlib,hashlib,importlib.util,io,json
import numpy as np

HERE=Path(__file__).resolve().parent;DEMO=HERE/'demo3d'


def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def read():
    return tuple(json.loads((DEMO/f).read_text()) for f in ['planning.json','tracking.json','tracking_validation.json','audit_results.json','video_validation.json'])


def validate(data):
    plan,track,valid,audit,video=data;errors=[]
    if valid['planning_sha256']!=sha(DEMO/'planning.json'):errors.append('Tracking uses a different reference')
    for f,digest in audit['input_sha256'].items():
        if sha(DEMO/f)!=digest:errors.append('Stale demo audit: '+f)
    for f,digest in video['input_sha256'].items():
        if sha(DEMO/f)!=digest:errors.append('Stale video source/data: '+f)
    if not audit['passed'] or not video['passed']:errors.append('Failed reference/video audit')
    if audit['exact_obstacle_polynomials']!=40 or audit['exact_floor_polynomials']!=5:errors.append('Wrong exact coverage')
    if audit['scalar_boundary_and_junction_checks']!=114:errors.append('Wrong affine coverage')
    if len(audit['negative_controls_rejected'])!=6:errors.append('Missing negative controls')
    if plan['inspection']['family']!=dict(d=7,k=4,l=4,N=5,eta=4):errors.append('Changed application family')
    if plan['frozen']['id']!='clutter_3d/05':errors.append('Changed frozen replay')
    if valid['primary']!=track['metrics']:errors.append('Tracking summaries disagree')
    if len(track['samples'])!=11001 or audit['tracking_rows_checked']!=11001:errors.append('Incomplete tracking log')
    if not all(valid[k]['passed'] for k in ['primary','half_step']):errors.append('Tracking replay failed')
    for key,value in audit['independently_recomputed_metrics'].items():
        if abs(valid['primary'][key]-value)>2e-12:errors.append('Changed audited metric: '+key)
    if video['decoded_frames']!=1536 or video['duration']!='64.000000':errors.append('Changed video duration')
    return errors


def render(write=False):
    data=read();errors=validate(data)
    if errors:raise AssertionError('\n'.join(errors))
    plan,track,v,audit,video=data;s=plan['inspection'];m=v['primary'];ds=v['integration_sensitivity']
    upper=lambda k:f"{ceil(s['derivative_bounds'][str(k)]['physical_bound']*10000)/10000:.4f}"
    macros=dict(QuadBodyRadius=f"{s['body_radius']:.2f}",QuadReserve=f"{s['tracking_reserve']:.2f}",
        QuadDuration=f"{s['duration']:.1f}",QuadMass=f"{v['mass']:.2f}",QuadRotorLimit=f"{v['max_rotor_thrust']:.2f}",
        QuadSpeedBound=upper(1),QuadAccelerationBound=upper(2),QuadJerkBound=upper(3),QuadRows=f"{len(track['samples']):,}",
        QuadNewPolys='25',QuadFrozenGap=f"{100*plan['frozen']['relative_gap_upper']:.2f}",
        QuadErrorSensitivity=f"{1000*ds['max_error_difference']:.4f}",QuadClearanceSensitivity=f"{1000*ds['min_clearance_difference']:.4f}")
    rows=[('Traversal / complete simulation',f"{s['duration']:.1f} / {track['total']:.1f} s"),
          ('Maximum tracking error',f"{100*m['max_error']:.2f} cm"),
          ('Minimum body clearance',f"{100*m['min_body_clearance']:.2f} cm"),
          ('Final position error',f"{1000*m['final_position_error']:.4f} mm"),
          ('Final speed',f"{1000*m['final_speed']:.4f} mm/s"),
          ('Maximum speed',f"{m['max_speed']:.3f} m/s"),
          ('Maximum tilt',f"{m['max_tilt_deg']:.2f}"+r'$^\circ$'),
          ('Maximum rotor thrust',f"{m['max_rotor_thrust']:.3f} N"),
          ('Clipped control updates / contact steps',f"{m['saturated_updates']} / {m['contact_steps']}")]
    table=('% Generated by quadrotor_results.py; do not edit.\n'
        '\\begin{table}[!t]\n\\caption{Illustrative quadrotor simulation. Extrema are sampled numerical measurements; the reference is checked separately in exact arithmetic.}\n'
        '\\label{tab:quadrotor}\n\\centering\\small\n\\begin{tabular}{@{}lr@{}}\n\\toprule\nQuantity & Value \\\\\n\\midrule\n'
        +'\n'.join(k+' & '+value+r' \\' for k,value in rows)+'\n\\bottomrule\n\\end{tabular}\n\\end{table}\n')
    claims=dict(scope='Developed illustrative simulation, not held-out or hardware validation',macros=macros,
        metrics=m,input_sha256={f:sha(DEMO/f) for f in ['planning.json','tracking.json','tracking_validation.json','scene_overview.jpg','scene_tracking.jpg']},video_sha256=video['sha256'])
    files={'results_quadrotor.tex':'% Generated from audited demo data.\n'+''.join('\\newcommand{\\'+k+'}{'+value+'}\n' for k,value in macros.items()),
           'table_quadrotor.tex':table,'claims_quadrotor.json':json.dumps(claims,indent=2)+'\n'}
    if write:
        for name,value in files.items():(HERE/name).write_text(value)
    return files


def recheck():
    path=DEMO/'audit_demo.py';spec=importlib.util.spec_from_file_location('application_audit',path)
    module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module)
    with contextlib.redirect_stdout(io.StringIO()):result=module.main()
    errors=validate(read())
    if errors:raise AssertionError('\n'.join(errors))
    return result


def plot():
    import matplotlib;matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from PIL import Image
    plan,track,valid,_,_=read();a=np.asarray(track['samples']);m=valid['primary']
    with plt.rc_context(figstyle.use()):
        fig=plt.figure(figsize=(figstyle.TEXT_W,4.1),layout='constrained');gs=fig.add_gridspec(2,2,height_ratios=[1.45,1])
        for j,(filename,title) in enumerate([('scene_overview.jpg','(a) Exactly checked reference'),('scene_tracking.jpg','(b) Simulated quadrotor')]):
            ax=fig.add_subplot(gs[0,j]);ax.imshow(Image.open(DEMO/filename));ax.set_axis_off();ax.set_title(title)
            if j==1:ax.text(.02,.04,f"Body-envelope diameter: {2*plan['inspection']['body_radius']:.2f} m",transform=ax.transAxes,color='black',fontsize=9,bbox=dict(facecolor='white',edgecolor='none',alpha=.9))
        ax=fig.add_subplot(gs[1,0]);ax.plot(a[:,0],100*a[:,11],color='#138d75',lw=1.5)
        ax.axhline(12,color='#ba8542',ls='--',lw=1,label='Allocated reserve')
        ax.set(xlim=(0,11),ylim=(-.5,15.5),xlabel='Simulation time (s)',ylabel='Position error (cm)',title='(c) Tracking error under disturbance')
        ax.text(.98,.44,f"Maximum: {100*m['max_error']:.2f} cm",ha='right',transform=ax.transAxes,fontsize=8)
        ax.legend(loc='upper right',frameon=False);ax.grid(alpha=.17)
        ax=fig.add_subplot(gs[1,1]);ax.plot(a[:,0],100*a[:,12],color='#294c70',lw=1.5);ax.axhline(0,color='#cd604d',lw=.8)
        ax.set(xlim=(0,11),xlabel='Simulation time (s)',ylabel='Body clearance (cm)',title='(d) Sampled body clearance')
        ax.text(.98,.78,f"Minimum: {100*m['min_body_clearance']:.2f} cm",ha='right',transform=ax.transAxes,fontsize=8,bbox=dict(facecolor='white',edgecolor='none',alpha=.9))
        ax.grid(alpha=.17)
        figstyle.save(fig,HERE/'fig_quadrotor_application')
        plt.close(fig)


if __name__=='__main__':
    render(write=True);plot();print('Generated verified quadrotor claims, table and application figure.')
